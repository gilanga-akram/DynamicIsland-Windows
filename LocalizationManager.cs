        private static LocalizationManager? _instance;
        public static LocalizationManager Instance => _instance ??= new LocalizationManager();

        public event Action? LanguageChanged;

        private string _currentLanguage = "id";
        public string CurrentLanguage => _currentLanguage;

        private readonly Dictionary<string, Dictionary<string, string>> _translations = new(StringComparer.OrdinalIgnoreCase);

        private LocalizationManager()
        {
            InitTranslations();
        }

        public void SetLanguage(string langCode)
        {
            if (string.IsNullOrWhiteSpace(langCode) || !_translations.ContainsKey(langCode))
            {
                langCode = "id";
            }

            if (_currentLanguage != langCode)
            {
                _currentLanguage = langCode;
                LanguageChanged?.Invoke();
            }
        }

        public string Get(string key, string fallback = "")
        {
            if (_translations.TryGetValue(_currentLanguage, out var dict) && dict.TryGetValue(key, out var text))
            {
                return text;
            }

            if (_translations.TryGetValue("en-US", out var enDict) && enDict.TryGetValue(key, out var enText))
            {
                return enText;
            }

            if (_translations.TryGetValue("id", out var idDict) && idDict.TryGetValue(key, out var idText))
            {
                return idText;
            }

            return fallback;
        }

